"""Build assets/kgr-sample.js from the Wikidata extract in materials/raw/ (CC0).

Inputs (fetched 2026-11-16, see official-course-map.md for the SPARQL and API calls):
  raw/laureates_raw.json      SPARQL result: every human with a Nobel Prize award statement + year
  raw/wikidata_entities.json  wbgetentities: labels and P69/P108/P184/P185/P27 for every person,
                              labels for every institution and country
Graph:
  persons  = laureates + their doctoral advisors + those advisors' advisors (2 levels up)
  edges    WON (person -> prize, year)      from P166 + P585 qualifier
           EDUCATED_AT (person -> org)       P69
           EMPLOYED_BY (person -> org)       P108
           ADVISED (advisor -> student)      P184 on the student or P185 on the advisor, both ends in the graph
           CITIZEN_OF (person -> country)    P27
Entities without an English label are dropped (counted in the report).
Output is json.dumps-generated, never string-built. Usage: python3 materials/build_kgr_sample.py
"""
import json, os, collections

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "raw")
OUT = os.path.join(HERE, "..", "assets", "kgr-sample.js")

PRIZES = [("Q38104", "Nobel Prize in Physics"), ("Q44585", "Nobel Prize in Chemistry"),
          ("Q80061", "Nobel Prize in Physiology or Medicine"), ("Q37922", "Nobel Prize in Literature"),
          ("Q35637", "Nobel Peace Prize"), ("Q47170", "Nobel Memorial Prize in Economic Sciences")]
ETYPES = ["WON", "EDUCATED_AT", "EMPLOYED_BY", "ADVISED", "CITIZEN_OF"]
KINDS = ["Person", "Institution", "Country", "Prize"]


def build():
    raw = json.load(open(os.path.join(RAW, "laureates_raw.json")))
    ent = json.load(open(os.path.join(RAW, "wikidata_entities.json")))
    qid = lambda u: u.rsplit("/", 1)[1]
    lau = sorted({qid(r["p"]) for r in raw["rows"]}, key=lambda q: int(q[1:]))
    L = set(lau)
    a1 = set()
    for q in lau:
        a1 |= set(ent[q]["claims"].get("P184", []))
    a1 -= L
    a2 = set()
    for q in a1:
        if ent.get(q) and "claims" in ent[q]:
            a2 |= set(ent[q]["claims"].get("P184", []))
    a2 -= L | a1
    persons = [q for q in sorted(L | a1 | a2, key=lambda q: int(q[1:])) if ent.get(q, {}).get("label")]
    P = set(persons)
    dropped = collections.Counter()
    dropped["person_no_label"] = len((L | a1 | a2) - P)

    nodes = []  # (kind, qid, label)
    idx = {}

    def add(kind, q, label):
        if q in idx:
            return idx[q]
        idx[q] = len(nodes)
        nodes.append((kind, q, label))
        return idx[q]

    for q in persons:
        add(0, q, ent[q]["label"])
    for q, lab in PRIZES:
        add(3, q, lab)

    edges = {t: [] for t in ETYPES}
    seen = set()

    def edge(t, a, b, extra=None):
        key = (t, a, b, extra)
        if key in seen:
            return
        seen.add(key)
        edges[t].append([a, b] + ([extra] if extra is not None else []))

    prize_q = {q for q, _ in PRIZES}
    for r in sorted(raw["rows"], key=lambda r: (int(qid(r["p"])[1:]), qid(r["prize"]), int(r.get("year", 0)))):
        p, z = qid(r["p"]), qid(r["prize"])
        if p in P and z in prize_q:
            edge("WON", idx[p], idx[z], int(r["year"]))

    def org(q, kind):
        lab = ent.get(q, {}).get("label")
        if not lab:
            dropped["org_or_country_no_label"] += 1
            return None
        if q in idx and nodes[idx[q]][0] != kind:
            # an entity used both as institution and country (rare): keep the first kind
            return idx[q]
        return add(kind, q, lab)

    for q in persons:
        c = ent[q]["claims"]
        for o in c.get("P69", []):
            j = org(o, 1)
            if j is not None:
                edge("EDUCATED_AT", idx[q], j)
        for o in c.get("P108", []):
            j = org(o, 1)
            if j is not None:
                edge("EMPLOYED_BY", idx[q], j)
        for o in c.get("P27", []):
            j = org(o, 2)
            if j is not None:
                edge("CITIZEN_OF", idx[q], j)
        for a in c.get("P184", []):
            if a in P and a != q:
                edge("ADVISED", idx[a], idx[q])
        for s in c.get("P185", []):
            if s in P and s != q:
                edge("ADVISED", idx[q], idx[s])

    for t in ETYPES:
        edges[t].sort()
    data = {
        "source": "Wikidata (CC0), extract fetched 2026-11-16",
        "kinds": KINDS,
        "etypes": ETYPES,
        "k": [n[0] for n in nodes],
        "q": [int(n[1][1:]) for n in nodes],
        "n": [n[2] for n in nodes],
        "e": edges,
    }
    return data, dropped


if __name__ == "__main__":
    data, dropped = build()
    js = ("/* kgr-sample.js - generated by materials/build_kgr_sample.py from Wikidata (CC0), fetched 2026-11-16.\n"
          "   Nobel laureates, their doctoral advisors two levels up, where they studied and worked, citizenship.\n"
          "   Do not edit by hand. */\n"
          "(function (root) { var D = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n"
          "if (typeof module !== \"undefined\" && module.exports) { module.exports = D; } else { root.KGR_DATA = D; }\n"
          "})(this);\n")
    open(OUT, "w", encoding="utf-8").write(js)
    kinds = collections.Counter(data["k"])
    print("bytes", len(js.encode("utf-8")), "nodes", len(data["k"]), dict(kinds),
          {t: len(v) for t, v in data["e"].items()}, dict(dropped))
